"""Build photos.js by scanning material-code folders in ./GALLERY.

Expected structure:
FG_Material_Gallery_Complete/
  index.html, gallery.css, script.js, materials.js, build_photo_index.py
  GALLERY/
    FNA-PE11005/
      FNA-PE11005(1).jpg
      FNA-PE11005(2).jpg
    2201168S1B/
      2201168S1B(1).jpg

Run: python build_photo_index.py
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
PHOTO_ROOT = ROOT / "GALLERY"
EXTENSIONS = {".jpg", ".jpeg", ".png", ".gif", ".webp", ".bmp", ".avif"}

if not PHOTO_ROOT.is_dir():
    raise SystemExit(
        "Can't find the GALLERY folder. Extract the contents of GALLERY.zip into a folder named 'GALLERY' beside this script, then run this again."
    )

index = {}
for folder in sorted((p for p in PHOTO_ROOT.iterdir() if p.is_dir()), key=lambda p: p.name.casefold()):
    images = sorted(
        (p for p in folder.rglob("*") if p.is_file() and p.suffix.lower() in EXTENSIONS),
        key=lambda p: p.name.casefold(),
    )
    if images:
        index[folder.name] = [p.relative_to(ROOT).as_posix() for p in images]

output = ROOT / "photos.js"
output.write_text("// Generated by build_photo_index.py.\nwindow.MATERIAL_PHOTOS = " + json.dumps(index, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"Indexed {sum(len(v) for v in index.values())} photos across {len(index)} material folders.")
print(f"Created: {output}")
